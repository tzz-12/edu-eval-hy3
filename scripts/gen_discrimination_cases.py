def main() -> int:
    base_path = ROOT / BASE_DOC
    if not base_path.exists():
        print(f"✗ 底稿不存在：{base_path}")
        return 1
    text = base_path.read_text(encoding="utf-8")

    cases = []
    for case_id, dim, level, ctype, desc, patches in CASES:
        built = []
        for p in patches:
            if len(p) == 2:                       # 整章替换
                key, new = p
                start, end = SECTIONS[key]
                old = slice_section(text, start, end)
            else:                                  # 精确片段替换
                _key, new, old = p
            if old not in text:
                print(f"✗ {case_id}：锚点未命中底稿\n    锚点前 60 字：{old[:60]}")
                return 1
            if old == new:
                print(f"✗ {case_id}：old 与 new 相同，等于没注入")
                return 1
            built.append({"old": old, "new": new})
        cases.append({
            "case_id": case_id, "dim": dim, "level": level,
            "type": ctype, "desc": desc, "patches": built,
        })
        tag = f"{len(built)}段" if len(built) > 1 else "1段 "
        print(f"✓ {case_id:14s} 维度{dim} {level:7s} {tag} "
              f"{sum(len(p['old']) for p in built):5d} 字 → "
              f"{sum(len(p['new']) for p in built):5d} 字  {desc[:26]}")

    payload = {
        "_comment": ("判别力实验注入用例。old 由 scripts/gen_discrimination_cases.py "
                     "按章节标记从底稿切片生成，改底稿后需重跑该脚本。"),
        "base_doc": BASE_DOC,
        "base_meta": {"grade": "七年级上册", "topic": "一元一次方程",
                      "version": "人教版", "lesson": "3.1 一元一次方程 第1课时"},
        "cases": cases,
    }
    CASES_FILE.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"\n写入 {len(cases)} 条用例 → {CASES_FILE.relative_to(ROOT)}")
    return 0


