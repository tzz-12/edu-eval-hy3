"""生成判别力注入用例定义（锚点从底稿切片，避免手打失配）。

为什么需要这个脚本
------------------
注入实验的关键前提是：mild 与 severe 档之间、以及它们与 base 之间，
**除目标缺陷外其余内容完全一致**。手打 `old` 锚点极易因一个空格、
一处标点而与底稿失配，导致注入静默失败（replace 找不到就原样返回，
实验照常跑完，结论却完全错）。

因此这里的 `old` 一律由「起止标记」从底稿文本中切出，
保证 100% 命中；注入内容由本脚本直接写入 cases 文件。

为什么有的用例要注入多段
------------------------
高质量教案的证据是**分布式**的：评价不只在「评价设计」一节，
每个教学环节的「反馈方式」也是评价证据；探究不只在「启发探究」一节，
新授环节的学生任务本身就是探究活动。

早期版本只在单一章节注入，结果 severe 档仍被判 5 分且证据未引用注入片段
——核查后确认 Judge 判得合理：文档其余部分确实还有真实证据。
因此重度/中度缺陷必须做**全文档级**注入，把该维度的证据一并清除，
否则测的是「注入是否够狠」而不是「评测器能否识别缺陷」。

用法
----
    python scripts/gen_discrimination_cases.py

产出
----
    data/testsets/discrimination_cases.json
"""
