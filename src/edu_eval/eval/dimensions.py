JUDGE_GROUPS = {
    "fact": ["2", "3"],
    "design": ["1", "4", "7", "8", "9"],
    "expression_safety": ["5", "6", "A"],
}

_DIM_BY_ID = {d.id: d for d in DIMENSIONS}


def get_dimension(dim_id: str) -> Dimension:
    return _DIM_BY_ID[dim_id]


def competency_map() -> dict[str, list[str]]:
    """返回 {维度 id → 主要服务的核心素养列表}。

    用于 Judge 提示词与报告层「素养覆盖」展示；本表与 dimensions 中
    competency_link 字段一致，是"评规版本"的一部分，修改需同步升 PROMPT_VERSION。
    """
    return {d.id: list(d.competency_link) for d in DIMENSIONS}


def weighted_total_weights() -> float:
    return sum(d.weight for d in DIMENSIONS if d.in_total)


def validate_weights() -> None:
    """校验加权维度权重之和为 100%（不含准入与辅助维度）。"""
    total = weighted_total_weights()
    if abs(total - 100.0) > 1e-6:
        raise ValueError(f"加权维度权重之和应为 100%，当前为 {total}%")


